-- Cada pedido copia os dados de entrega e o preço do livro do momento da venda.
WITH compras AS (
    SELECT e.*, l.id_livro, l.preco, l.titulo, l.caminho_imagem_livro,
           q.quantidade, l.preco * q.quantidade AS subtotal, q.dias,
           CASE WHEN q.livro_id % 2 = 1 THEN ROUND(l.preco * q.quantidade * 0.05, 2)
                ELSE 0 END AS desconto
    FROM (VALUES (1,1,1,30), (2,2,2,28), (3,3,1,26), (4,4,1,24), (5,5,2,22),
                 (6,6,1,20), (7,7,1,8), (8,8,1,6), (9,9,2,4), (10,10,1,2))
         AS q(cliente_id, livro_id, quantidade, dias)
    JOIN public.enderecos_clientes e
