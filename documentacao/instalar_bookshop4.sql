-- 1. Pessoas, catálogo e estrutura de compras
CREATE TABLE public.pessoas (
  cpf_pessoa VARCHAR(14) PRIMARY KEY
    CONSTRAINT pessoas_cpf_formato_check
    CHECK (cpf_pessoa ~ '^([0-9]{11}|[0-9]{3}[.][0-9]{3}[.][0-9]{3}-[0-9]{2})$'),
  nome_pessoa VARCHAR(100) NOT NULL CHECK (BTRIM(nome_pessoa) <> ''),
  data_nascimento_pessoa DATE NOT NULL,
  endereco_pessoa VARCHAR(200),
  nome_usuario_pessoa VARCHAR(50) NOT NULL CHECK (BTRIM(nome_usuario_pessoa) <> ''),
  email_pessoa VARCHAR(150) NOT NULL,
  senha_pessoa VARCHAR(255) NOT NULL,
  CHECK (POSITION('@' IN email_pessoa) > 1)
);
CREATE UNIQUE INDEX uq_pessoas_usuario_lower
  ON public.pessoas (LOWER(BTRIM(nome_usuario_pessoa)));
CREATE UNIQUE INDEX uq_pessoas_email_lower
  ON public.pessoas (LOWER(BTRIM(email_pessoa)));
CREATE UNIQUE INDEX uq_pessoas_cpf_digits
  ON public.pessoas (REGEXP_REPLACE(cpf_pessoa, '[^0-9]', '', 'g'));

CREATE TABLE public.cargos (
  id_cargo SERIAL PRIMARY KEY,
  nome_cargo VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE public.clientes (
  pessoa_cpf_pessoa VARCHAR(14) PRIMARY KEY
    REFERENCES public.pessoas(cpf_pessoa) ON DELETE RESTRICT,
  renda_cliente NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (renda_cliente >= 0),
  data_cadastro_cliente DATE NOT NULL DEFAULT CURRENT_DATE
);
CREATE TABLE public.funcionarios (
  pessoa_cpf_pessoa VARCHAR(14) PRIMARY KEY
    REFERENCES public.pessoas(cpf_pessoa) ON DELETE RESTRICT,
  salario_funcionario NUMERIC(10,2) NOT NULL DEFAULT 0
    CHECK (salario_funcionario >= 0),
  cargo_id_cargo INTEGER NOT NULL
    REFERENCES public.cargos(id_cargo) ON DELETE RESTRICT,
  porcentagem_comissao_funcionario NUMERIC(5,2) NOT NULL DEFAULT 0
    CHECK (porcentagem_comissao_funcionario BETWEEN 0 AND 100)
);
CREATE INDEX idx_funcionarios_cargo ON public.funcionarios(cargo_id_cargo);

CREATE TABLE public.generos (
  id_genero SERIAL PRIMARY KEY,
  nome_genero VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE public.livros (
  id_livro SERIAL PRIMARY KEY,
  ordem_cadastro BIGINT GENERATED ALWAYS AS IDENTITY,
  titulo VARCHAR(200) NOT NULL,
  autor VARCHAR(150) NOT NULL,
  isbn VARCHAR(20) UNIQUE,
  editora VARCHAR(100),
  paginas INTEGER NOT NULL CHECK (paginas > 0),
  ano INTEGER CHECK (ano IS NULL OR (ano > 0 AND ano <= 2100)),
  sinopse TEXT,
  preco NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
  estoque INTEGER NOT NULL DEFAULT 0 CHECK (estoque >= 0),
  genero_id INTEGER NOT NULL REFERENCES public.generos(id_genero) ON DELETE RESTRICT,
  caminho_imagem_livro VARCHAR(255)
);
CREATE INDEX idx_livros_genero ON public.livros(genero_id);
CREATE INDEX idx_livros_titulo_lower ON public.livros(LOWER(titulo));

CREATE TABLE public.lancamentos (
  id_lancamento SERIAL PRIMARY KEY,
  livro_id_livro INTEGER NOT NULL UNIQUE
    REFERENCES public.livros(id_livro) ON DELETE CASCADE,
  pais_lancamento VARCHAR(100) NOT NULL,
  data_lancamento DATE NOT NULL
);
CREATE TABLE public.enderecos_clientes (
  id_endereco BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_pessoa_cpf_pessoa VARCHAR(14) NOT NULL
    REFERENCES public.clientes(pessoa_cpf_pessoa) ON DELETE CASCADE,
  cep VARCHAR(9) NOT NULL CHECK (cep ~ '^[0-9]{5}-?[0-9]{3}$'),
  rua VARCHAR(200) NOT NULL CHECK (BTRIM(rua) <> ''),
  numero VARCHAR(30) NOT NULL CHECK (BTRIM(numero) <> ''),
  complemento VARCHAR(100),
  bairro VARCHAR(100) NOT NULL CHECK (BTRIM(bairro) <> ''),
  cidade VARCHAR(100) NOT NULL CHECK (BTRIM(cidade) <> ''),
  estado VARCHAR(2) NOT NULL CHECK (estado ~ '^[A-Za-z]{2}$'),
  principal BOOLEAN NOT NULL DEFAULT FALSE,
  data_criacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_enderecos_cliente
  ON public.enderecos_clientes(cliente_pessoa_cpf_pessoa);
CREATE UNIQUE INDEX uq_enderecos_cliente_principal
  ON public.enderecos_clientes(cliente_pessoa_cpf_pessoa)
  WHERE principal;

CREATE TABLE public.formas_pagamento (
  id_forma_pagamento SERIAL PRIMARY KEY,
  nome_forma_pagamento VARCHAR(100) NOT NULL UNIQUE,
  ativa BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE public.pedidos (
  id_pedido SERIAL PRIMARY KEY,
  data_pedido DATE NOT NULL DEFAULT CURRENT_DATE,
  cliente_pessoa_cpf_pessoa VARCHAR(14)
    REFERENCES public.clientes(pessoa_cpf_pessoa),
  status_pedido VARCHAR(30) NOT NULL DEFAULT 'Em preparação'
    CONSTRAINT pedidos_status_pedido_check CHECK (status_pedido IN (
      'Aguardando confirmação', 'Em preparação', 'Confirmado para entrega',
      'Enviado para entrega', 'Atraso', 'Cancelado', 'Concluído'
    )),
  data_prevista_entrega DATE,
  total_pedido NUMERIC(12,2) NOT NULL CHECK (total_pedido >= 0),
  subtotal_pedido NUMERIC(12,2) CHECK (subtotal_pedido >= 0),
  desconto_pedido NUMERIC(12,2) CHECK (desconto_pedido >= 0),
  frete_pedido NUMERIC(12,2) CHECK (frete_pedido >= 0),
  endereco_entrega_id BIGINT
    REFERENCES public.enderecos_clientes(id_endereco) ON DELETE SET NULL,
  endereco_entrega_cep VARCHAR(9),
  endereco_entrega_rua VARCHAR(200),
  endereco_entrega_numero VARCHAR(30),
  endereco_entrega_complemento VARCHAR(100),
  endereco_entrega_bairro VARCHAR(100),
  endereco_entrega_cidade VARCHAR(100),
  endereco_entrega_estado VARCHAR(2),
  cliente_fisico BOOLEAN NOT NULL DEFAULT FALSE,
  detalhes_pedido TEXT,
  nome_cliente_presencial VARCHAR(150),
  telefone_cliente_presencial VARCHAR(30),
  atraso_manual BOOLEAN NOT NULL DEFAULT FALSE,
  enviado_em TIMESTAMPTZ,
  ocultar_cancelado_cliente BOOLEAN NOT NULL DEFAULT FALSE,
  desconto_registro JSONB,
  primeira_compra_utilizada BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_pedido_primeira_compra
  ON public.pedidos(cliente_pessoa_cpf_pessoa) WHERE primeira_compra_utilizada;
CREATE INDEX idx_pedidos_cliente_data
  ON public.pedidos(cliente_pessoa_cpf_pessoa, data_pedido DESC);

CREATE TABLE public.pedido_has_livro (
  livro_id_livro INTEGER NOT NULL REFERENCES public.livros(id_livro),
  pedido_id_pedido INTEGER NOT NULL
    REFERENCES public.pedidos(id_pedido) ON DELETE CASCADE,
  quantidade INTEGER NOT NULL CHECK (quantidade > 0),
  preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario >= 0),
  titulo_livro VARCHAR(200),
  caminho_imagem_livro VARCHAR(255),
  total_item NUMERIC(12,2) CHECK (total_item >= 0),
  PRIMARY KEY (livro_id_livro, pedido_id_pedido)
);
CREATE INDEX idx_itens_pedido ON public.pedido_has_livro(pedido_id_pedido);
CREATE INDEX idx_itens_livro ON public.pedido_has_livro(livro_id_livro);

CREATE TABLE public.pagamentos (
  pedido_id_pedido INTEGER PRIMARY KEY
    REFERENCES public.pedidos(id_pedido) ON DELETE CASCADE,
  data_pagamento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  valor_total_pagamento NUMERIC(12,2) NOT NULL CHECK (valor_total_pagamento >= 0),
  status_pagamento VARCHAR(30) NOT NULL DEFAULT 'Aguardando confirmação'
    CHECK (status_pagamento IN (
      'Aguardando confirmação', 'Simulado', 'Cancelado'
    )),
  forma_pagamento_id_forma_pagamento INTEGER NOT NULL
    REFERENCES public.formas_pagamento(id_forma_pagamento),
  tentativa_id UUID,
  pix_qr_code TEXT,
  pix_qr_code_base64 TEXT
);
CREATE UNIQUE INDEX uq_pagamentos_tentativa_id
  ON public.pagamentos(tentativa_id)
  WHERE tentativa_id IS NOT NULL;

CREATE TABLE public.tokens_recuperacao_senha (
  id BIGSERIAL PRIMARY KEY,
  cpf_pessoa VARCHAR(14) NOT NULL REFERENCES public.pessoas(cpf_pessoa) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expira_em TIMESTAMPTZ NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_tokens_recuperacao_cpf ON public.tokens_recuperacao_senha(cpf_pessoa);

-- 2. Histórico, solicitações de cancelamento e promoções
CREATE TABLE public.pedido_eventos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INTEGER NOT NULL REFERENCES public.pedidos(id_pedido),
  autor_cpf VARCHAR(14) REFERENCES public.pessoas(cpf_pessoa) ON DELETE SET NULL,
  estado VARCHAR(30) NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  percentual SMALLINT CHECK (percentual IN (50, 75, 100)),
  reembolso NUMERIC(12,2) CHECK (reembolso >= 0),
  situacao VARCHAR(12) CHECK (situacao IN ('Pendente', 'Simulado')),
  estoque_reposto BOOLEAN NOT NULL DEFAULT FALSE,
  processado_em TIMESTAMPTZ,
  estado_anterior VARCHAR(40),
  motivo TEXT,
  historico_legado_id BIGINT UNIQUE,
  CHECK (num_nonnulls(percentual, reembolso, situacao) IN (0, 3))
);
CREATE INDEX idx_pedido_eventos_pedido ON public.pedido_eventos(pedido_id, id);
CREATE UNIQUE INDEX uq_pedido_reembolso ON public.pedido_eventos(pedido_id)
  WHERE percentual IS NOT NULL;

CREATE TABLE public.solicitacoes_cancelamento (
  pedido_id INTEGER PRIMARY KEY REFERENCES public.pedidos(id_pedido),
  motivo TEXT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  estado VARCHAR(12) NOT NULL DEFAULT 'Pendente' CHECK (estado IN ('Pendente','Aprovada','Recusada')),
  resposta TEXT,
  analisado_em TIMESTAMPTZ,
  anexo BYTEA,
  tipo_anexo VARCHAR(20),
  CHECK ((anexo IS NULL) = (tipo_anexo IS NULL)),
  CHECK (octet_length(anexo) <= 10485760),
  CHECK (tipo_anexo IN ('image/jpeg','image/png','video/mp4','video/webm'))
);

CREATE TABLE public.promocoes (
  codigo VARCHAR(50) PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  descricao TEXT,
  tipo VARCHAR(60) NOT NULL DEFAULT 'Campanha',
  criterios JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(criterios) = 'object'),
  combinacao VARCHAR(2) NOT NULL DEFAULT 'E' CHECK (combinacao IN ('E', 'OU')),
  combinavel BOOLEAN NOT NULL DEFAULT FALSE,
  percentual SMALLINT NOT NULL CHECK (percentual BETWEEN 1 AND 100),
  inicio TIMESTAMPTZ,
  termino TIMESTAMPTZ,
  ativa BOOLEAN NOT NULL DEFAULT FALSE,
  CHECK (termino IS NULL OR inicio IS NULL OR termino > inicio),
  CHECK (NOT ativa OR (inicio IS NOT NULL AND (codigo <> 'bookfriday' OR termino IS NOT NULL)))
);

CREATE INDEX idx_promocoes_periodo ON public.promocoes(inicio, termino) WHERE ativa;

